"""Write references/helpers.md: every public function in scripts/blender/ with its signature and
the first line of its docstring, read from the code (ast, nothing imported).

    python scripts/helper_index.py

Run it after adding or changing a helper (maintaining.md), so the index never drifts.
"""
import ast
import os
from pathlib import Path

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "blender")
OUT = os.path.join(os.path.dirname(HERE), "references", "helpers.md")


def sig(fn):
    a = fn.args
    pos = a.posonlyargs + a.args
    defaults = [None] * (len(pos) - len(a.defaults)) + a.defaults
    parts = [p.arg + ("=" + ast.unparse(d) if d is not None else "") for p, d in zip(pos, defaults)]
    if a.vararg:
        parts.append("*" + a.vararg.arg)
    elif a.kwonlyargs:
        parts.append("*")
    parts += [k.arg + ("=" + ast.unparse(d) if d is not None else "") for k, d in zip(a.kwonlyargs, a.kw_defaults)]
    if a.kwarg:
        parts.append("**" + a.kwarg.arg)
    return "(" + ", ".join(parts) + ")"


def first_line(node):
    doc = ast.get_docstring(node) or ""
    return " ".join(doc.strip().split("\n\n")[0].split())


rows = ["# Helper index (generated by `scripts/helper_index.py` — do not edit by hand)", "",
        "Public functions in `scripts/blender/`, read from the code. Use these before writing node",
        "plumbing yourself; the module docstrings and `references/` explain the methods.", ""]
for path in sorted(Path(SRC).rglob("*.py")):
    if path.name == "__init__.py":
        continue
    f = path.relative_to(SRC).with_suffix("").as_posix().replace("/", ".")
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    items = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and not n.name.startswith("_")]
    if not items:
        continue
    mod_doc = first_line(tree)
    rows += [f"## `{f}`" + (f" — {mod_doc}" if mod_doc else ""), ""]
    for n in items:
        s = sig(n) if isinstance(n, ast.FunctionDef) else ""
        d = first_line(n)
        rows.append(f"- `{n.name}{s}`" + (f" — {d}" if d else ""))
    rows.append("")
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(rows))
print("wrote", OUT, sum(1 for r in rows if r.startswith("- ")), "helpers")
