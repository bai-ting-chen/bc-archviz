"""Write references/scene/blender-python-helpers.md: every module in scripts/blender/ with the first sentence of
its docstring and the names of its public functions and classes, read from the code (ast, nothing imported).

    python scripts/workflow/helper_index.py

Run it after adding or changing a helper (skill-maintaining.md), so the index never drifts. Signatures are left
out on purpose: the index is read on every run, the module itself holds the signature and docstring.
"""
import ast
import os
import re
from pathlib import Path

WORKFLOW_DIR = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.dirname(WORKFLOW_DIR)
BLENDER_SCRIPTS_DIR = os.path.join(SCRIPTS, "blender")
HELPER_REFERENCE_PATH = os.path.join(os.path.dirname(SCRIPTS), "references", "scene", "blender-python-helpers.md")

# Docstrings that only restate the module name ("Gravel; canonical implementation behind ground.") add nothing.
PLACEHOLDER_DOCSTRING = re.compile(r"canonical implementations?|implementation for", re.IGNORECASE)


def first_sentence(node):
    doc = " ".join((ast.get_docstring(node) or "").strip().split("\n\n")[0].split())
    match = re.match(r"(.+?[.!?])(\s|$)", doc)
    return match.group(1) if match else doc


rows = ["# Blender Python helpers (generated by `scripts/workflow/helper_index.py` — do not edit by hand)", "",
        "Public functions and classes in `scripts/blender/`, by package. Use these before writing node",
        "plumbing yourself. For a signature, read the module's file under `scripts/blender/` (package path = folders);",
        "its docstrings explain each helper, and `references/` explain the methods. `core.archviz` re-exports",
        "the everyday helpers (import, UVs, camera, HDRI, render set-up, assets).", ""]
modules = sorted(((path.relative_to(BLENDER_SCRIPTS_DIR).with_suffix(""), path)
                  for path in Path(BLENDER_SCRIPTS_DIR).rglob("*.py") if path.name != "__init__.py"),
                 key=lambda item: (item[0].parent.as_posix(), item[0].name))   # a package's modules stay together
current_package = None
for relative, path in modules:
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read())
    names = [n.name for n in tree.body
             if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and not n.name.startswith("_")]
    if not names:
        continue
    package = relative.parent.as_posix().replace("/", ".")
    if package != current_package:
        rows += ([""] if current_package else []) + [f"## `{package}`", ""]
        current_package = package
    summary = first_sentence(tree)
    summary = "" if PLACEHOLDER_DOCSTRING.search(summary) else f" — {summary}"
    rows.append(f"- `{relative.name}`: " + ", ".join(f"`{name}`" for name in names) + summary)
rows.append("")
with open(HELPER_REFERENCE_PATH, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(rows))
print("wrote", HELPER_REFERENCE_PATH, sum(1 for r in rows if r.startswith("- ")), "modules")
